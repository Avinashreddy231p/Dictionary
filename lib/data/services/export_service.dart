class ExportService {
  /// Converts saved words to full schema JSON backup string.
  static String exportToFullJson(List<SavedWord> words) {
    final jsonList = words
        .map((w) => {
              'word': w.word,
              'phonetic': w.phonetic,
              'partOfSpeech': w.partOfSpeech,
              'meaning': w.meaning,
              'example': w.example,
              'syllables': w.syllables,
              'cefr': w.cefr,
              'dateAdded': w.dateAdded.toIso8601String(),
              'contextSentence': w.contextSentence,
              'personalNote': w.personalNote,
              'reviewState': w.reviewState,
              'isFavorite': w.isFavorite,
              'source': w.source,
            })
        .toList();

    return const JsonEncoder.withIndent('  ').convert(jsonList);
  }

  /// Converts a list of saved vocabulary words to Anki-compatible CSV text.
  /// Format: word;partOfSpeech;phonetic;meaning;example;source
  static String exportToAnkiCsv(List<SavedWord> words) {
    final sb = StringBuffer();
    sb.writeln('# Anki Deck Export generated by Dictionary App');
    sb.writeln('# Format: Word;Part of Speech;Phonetics;Meaning;Example;Source');

    for (final w in words) {
      final word = _cleanField(w.word);
      final pos = _cleanField(w.partOfSpeech ?? '');
      final phonetic = _cleanField(w.phonetic ?? '');
      final meaning = _cleanField(w.meaning ?? '');
      final example = _cleanField(w.example ?? '');
      final source = _cleanField(w.source ?? '');

      sb.writeln('$word;$pos;$phonetic;$meaning;$example;$source');
    }

    return sb.toString();
  }

  /// Converts a list of saved vocabulary words into a formatted Study Sheet.
  static String exportToFormattedStudySheet(List<SavedWord> words, String title) {
    final sb = StringBuffer();
    sb.writeln('===================================================');
    sb.writeln('📖 VOCABULARY STUDY SHEET: $title');
    sb.writeln('Total Words: ${words.length}');
    sb.writeln('===================================================\n');

    for (int i = 0; i < words.length; i++) {
      final w = words[i];
      sb.writeln('${i + 1}. ${w.word.toUpperCase()} [${w.partOfSpeech ?? 'word'}] ${w.phonetic ?? ''}');
      sb.writeln('   Definition: ${w.meaning ?? 'N/A'}');
      if (w.example != null && w.example!.isNotEmpty) {
        sb.writeln('   Example: "${w.example}"');
      }
      if (w.contextSentence != null && w.contextSentence!.isNotEmpty) {
        sb.writeln('   Context: "${w.contextSentence}"');
      }
      sb.writeln('');
    }

    return sb.toString();
  }

  /// Generates a real, valid binary PDF document bytes (.pdf)
  static Future<Uint8List> generatePdfDocument(List<SavedWord> words, String title) async {
    final pdf = pw.Document();

    // Load full Unicode IPA compliant font (Noto Sans)
    final fontBase = await PdfGoogleFonts.notoSansRegular();
    final fontBold = await PdfGoogleFonts.notoSansBold();
    final fontItalic = await PdfGoogleFonts.notoSansItalic();

    pdf.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.all(32),
        theme: pw.ThemeData.withFont(
          base: fontBase,
          bold: fontBold,
          italic: fontItalic,
        ),
        build: (pw.Context context) {
          return [
            pw.Header(
              level: 0,
              child: pw.Row(
                mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
                children: [
                  pw.Text(
                    title.toUpperCase(),
                    style: pw.TextStyle(
                      fontSize: 20,
                      fontWeight: pw.FontWeight.bold,
                      color: PdfColors.deepPurple900,
                    ),
                  ),
                  pw.Container(
                    padding: const pw.EdgeInsets.symmetric(horizontal: 10, vertical: 4),
                    decoration: pw.BoxDecoration(
                      color: PdfColors.deepPurple100,
                      borderRadius: pw.BorderRadius.circular(8),
                    ),
                    child: pw.Text(
                      '${words.length} Vocabulary Words',
                      style: pw.TextStyle(
                        fontSize: 11,
                        fontWeight: pw.FontWeight.bold,
                        color: PdfColors.deepPurple900,
                      ),
                    ),
                  ),
                ],
              ),
            ),
            pw.SizedBox(height: 12),
            pw.Divider(color: PdfColors.grey400),
            pw.SizedBox(height: 12),

            ...words.asMap().entries.map((entry) {
              final idx = entry.key + 1;
              final w = entry.value;

              return pw.Container(
                margin: const pw.EdgeInsets.only(bottom: 12),
                padding: const pw.EdgeInsets.all(12),
                decoration: pw.BoxDecoration(
                  color: PdfColors.grey100,
                  borderRadius: pw.BorderRadius.circular(10),
                  border: pw.Border.all(color: PdfColors.grey300),
                ),
                child: pw.Column(
                  crossAxisAlignment: pw.CrossAxisAlignment.start,
                  children: [
                    pw.Row(
                      children: [
                        pw.Text(
                          '$idx. ${w.word.toUpperCase()}',
                          style: pw.TextStyle(
                            fontSize: 13,
                            fontWeight: pw.FontWeight.bold,
                            color: PdfColors.black,
                          ),
                        ),
                        if (w.partOfSpeech != null && w.partOfSpeech!.isNotEmpty) ...[
                          pw.SizedBox(width: 8),
                          pw.Text(
                            '[${w.partOfSpeech}]',
                            style: pw.TextStyle(
                              fontSize: 10,
                              fontStyle: pw.FontStyle.italic,
                              color: PdfColors.deepPurple700,
                            ),
                          ),
                        ],
                        if (w.phonetic != null && w.phonetic!.isNotEmpty) ...[
                          pw.SizedBox(width: 8),
                          pw.Text(
                            w.phonetic!,
                            style: const pw.TextStyle(
                              fontSize: 10,
                              color: PdfColors.grey700,
                            ),
                          ),
                        ],
                      ],
                    ),
                    pw.SizedBox(height: 4),
                    pw.Text(
                      'Definition: ${w.meaning ?? 'N/A'}',
                      style: const pw.TextStyle(fontSize: 11),
                    ),
                    if (w.example != null && w.example!.isNotEmpty) ...[
                      pw.SizedBox(height: 4),
                      pw.Text(
                        'Example: "${w.example}"',
                        style: pw.TextStyle(
                          fontSize: 10,
                          fontStyle: pw.FontStyle.italic,
                          color: PdfColors.grey800,
                        ),
                      ),
                    ],
                  ],
                ),
              );
            }).toList(),
          ];
        },
        footer: (pw.Context context) {
          return pw.Container(
            alignment: pw.Alignment.centerRight,
            margin: const pw.EdgeInsets.only(top: 10),
            child: pw.Text(
              'Page ${context.pageNumber} of ${context.pagesCount} • Generated by Dictionary App',
              style: const pw.TextStyle(fontSize: 9, color: PdfColors.grey600),
            ),
          );
        },
      ),
    );

    return pdf.save();
  }

  /// Exports binary data (like a real PDF document) to a local file and opens Native Share Sheet!
  static Future<void> exportAndShareBytes({
    required BuildContext context,
    required String filename,
    required Uint8List bytes,
    required String successMessage,
  }) async {
    try {
      final tempDir = await getTemporaryDirectory();
      final cleanName = filename.replaceAll(RegExp(r'[^\w.-]'), '_');
      final file = File('${tempDir.path}/$cleanName');
      await file.writeAsBytes(bytes);

      await Share.shareXFiles(
        [XFile(file.path)],
        text: 'Exported document: $cleanName',
      );
    } catch (e) {
      if (context.mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(
            content: Text('Failed to export document: $e'),
            behavior: SnackBarBehavior.floating,
          ),
        );
      }
    }
  }

  /// Creates a temporary export text file AND opens the native OS Share Sheet!
  static Future<void> exportAndShareFile({
    required BuildContext context,
    required String filename,
    required String content,
    required String successMessage,
  }) async {
    try {
      final tempDir = await getTemporaryDirectory();
      final cleanName = filename.replaceAll(RegExp(r'[^\w.-]'), '_');
      final file = File('${tempDir.path}/$cleanName');
      await file.writeAsString(content);

      // Native System Share Sheet with file attached!
      await Share.shareXFiles(
        [XFile(file.path)],
        text: 'Exported vocabulary collection: $cleanName',
      );
    } catch (_) {
      await copyToClipboard(context, content, '$successMessage (Content copied)');
    }
  }

  static Future<void> copyToClipboard(BuildContext context, String content, String message) async {
    await Clipboard.setData(ClipboardData(text: content));
    if (context.mounted) {
      ScaffoldMessenger.of(context).hideCurrentSnackBar();
      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(
          content: Text(message),
          behavior: SnackBarBehavior.floating,
          duration: const Duration(seconds: 2),
        ),
      );
    }
  }

  static String _cleanField(String input) {
    return input.replaceAll(';', ',').replaceAll('\n', ' ').trim();
  }
}
